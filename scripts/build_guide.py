# ─── Сборка ────────────────────────────────────────────────────────────
def build():
    out_dir = Path(__file__).resolve().parent.parent / "docs"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / "guide.pdf"

    doc = SimpleDocTemplate(
        str(out),
        pagesize=A4,
        leftMargin=2 * cm, rightMargin=2 * cm,
        topMargin=2 * cm, bottomMargin=2 * cm,
        title="Baqsy · Digital Baqsylyq · Руководство пользователя",
        author="Baqsy",
    )

    story: list = []
    story += cover_page()
    story += section_about()
    story += section_for_client()
    story += section_for_admin()
    story += section_faq()
    story += section_contacts()

    def on_page(canvas, doc):
        canvas.saveState()
        page_num = canvas.getPageNumber()
        if page_num > 1:
            canvas.setFont(REGULAR, 8)
            canvas.setFillColor(INK_500)
            canvas.drawRightString(
                A4[0] - 2 * cm, 1.2 * cm,
                f"Baqsy · Digital Baqsylyq · стр. {page_num}",
            )
            canvas.setFillColor(BRAND_500)
            canvas.rect(0, A4[1] - 2 * mm, A4[0], 2 * mm, fill=1, stroke=0)
        canvas.restoreState()

    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    size_kb = os.path.getsize(out) / 1024
    print(f"Generated: {out} ({size_kb:.0f} KB)")


if __name__ == "__main__":
    build()
